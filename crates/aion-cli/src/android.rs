fn generate_app_build_gradle(opts: &AndroidBuildOptions) -> String {
    let signing_block = match (
        &opts.keystore,
        &opts.keystore_pass,
        &opts.key_alias,
        &opts.key_pass,
    ) {
        (Some(ks), Some(kp), Some(alias), Some(keyp)) => {
            let ks_escaped = ks.display().to_string().replace('\\', "\\\\");
            format!(
                r#"
    signingConfigs {{
        create("release") {{
            storeFile = file("{ks_escaped}")
            storePassword = "{kp}"
            keyAlias = "{alias}"
            keyPassword = "{keyp}"
        }}
    }}"#
            )
        }
        _ => String::new(),
    };

    let release_signing = if opts.keystore.is_some()
        && opts.keystore_pass.is_some()
        && opts.key_alias.is_some()
        && opts.key_pass.is_some()
    {
        "            signingConfig = signingConfigs.getByName(\"release\")\n"
    } else {
        ""
    };

    format!(
        r#"plugins {{
    id("com.android.application")
}}

android {{
    namespace = "{app_id}"
    compileSdk = 35

    defaultConfig {{
        applicationId = "{app_id}"
        minSdk = 24
        targetSdk = 35
        versionCode = {version_code}
        versionName = "{version_name}"
    }}
{signing_block}

    buildTypes {{
        release {{
            isMinifyEnabled = false
{release_signing}        }}
    }}

    compileOptions {{
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }}

    bundle {{
        language {{
            enableSplit = false
        }}
        density {{
            enableSplit = true
        }}
        abi {{
            enableSplit = true
        }}
    }}
}}
"#,
        app_id = opts.app_id,
        version_code = opts.version_code,
        version_name = opts.version_name,
        signing_block = signing_block,
        release_signing = release_signing,
    )
}

fn generate_manifest(app_name: &str) -> String {
    let safe_name = app_name
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;");
    format!(
        r#"<?xml version="1.0" encoding="utf-8"?>
<manifest xmlns:android="http://schemas.android.com/apk/res/android">
    <uses-permission android:name="android.permission.INTERNET" />
    <uses-permission android:name="android.permission.VIBRATE" />
    <uses-permission android:name="android.permission.POST_NOTIFICATIONS" />

    <application
        android:label="{safe_name}"
        android:usesCleartextTraffic="true"
        android:theme="@android:style/Theme.Material.Light.NoActionBar">
        <activity
            android:name=".MainActivity"
            android:exported="true">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity>
    </application>
</manifest>
"#
    )
}

