#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AndroidBuildOptions {
    pub app_id: String,
    pub app_name: String,
    pub version_code: u32,
    pub version_name: String,
    pub api_base_url: Option<String>,
    pub out_dir: PathBuf,
    pub debug: bool,
    pub generate_only: bool,
    pub keystore: Option<PathBuf>,
    pub keystore_pass: Option<String>,
    pub key_alias: Option<String>,
    pub key_pass: Option<String>,
}

impl Default for AndroidBuildOptions {
    fn default() -> Self {
        Self {
            app_id: "com.aion.app".to_string(),
            app_name: "AION App".to_string(),
            version_code: 1,
            version_name: "0.1.0".to_string(),
            api_base_url: None,
            out_dir: PathBuf::from("build/android"),
            debug: false,
            generate_only: false,
            keystore: None,
            keystore_pass: None,
            key_alias: None,
            key_pass: None,
        }
    }
}

#[derive(Debug, Clone, Serialize)]
pub struct AndroidBuildResult {
    pub ok: bool,
    pub app_id: String,
    pub app_name: String,
    pub version_code: u32,
    pub version_name: String,
    pub project_dir: String,
    pub bundle_json_path: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub aab_path: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub aab_size_bytes: Option<u64>,
    pub mode: String,
}

/// Generates a self-contained native Android project for `program` and compiles an
/// Android App Bundle (`.aab`) via Gradle (`:app:bundleRelease` or `:app:bundleDebug`).
pub fn build_android_aab(
    program: &Program,
    opts: &AndroidBuildOptions,
) -> Result<AndroidBuildResult, String> {
    validate_app_id(&opts.app_id)?;

    let project_dir = &opts.out_dir;
    let app_dir = project_dir.join("app");
    let pkg_rel_path = opts.app_id.replace('.', "/");
    let java_dir = app_dir.join("src/main/java").join(&pkg_rel_path);
    let assets_dir = app_dir.join("src/main/assets");

    fs::create_dir_all(&java_dir)
        .map_err(|e| format!("failed to create {}: {e}", java_dir.display()))?;
    fs::create_dir_all(&assets_dir)
        .map_err(|e| format!("failed to create {}: {e}", assets_dir.display()))?;

    // 1. Precompute mobile (390x844) Taffy layout + Signals + AST + .proto bundle.
    let signal_store = SignalStore::from_program(program);
    let mut initial_signals = serde_json::Map::new();
    for node in &program.nodes {
        if let NodeKind::Signal(_) = &node.kind {
            if let Some(val) = signal_store.get(&node.id) {
                initial_signals.insert(
                    node.id.as_str().to_string(),
                    serde_json::to_value(val).unwrap_or(serde_json::Value::Null),
                );
            }
        }
    }
    let layout = compute_layout(program, Viewport::MOBILE, Some(&signal_store))
        .map_err(|e| format!("layout error: {e}"))?;
    let proto = generate_proto3(program);
    let default_port = extract_port(program).unwrap_or(8080);
    let api_base_url = opts
        .api_base_url
        .clone()
        .unwrap_or_else(|| format!("http://10.0.2.2:{default_port}"));

    let bundle_payload = json!({
        "apiBaseUrl": api_base_url,
        "program": program,
        "signals": initial_signals,
        "layout": layout,
        "proto": proto,
    });
    let bundle_json_path = assets_dir.join("aion_bundle.json");
    fs::write(
        &bundle_json_path,
        serde_json::to_string_pretty(&bundle_payload).unwrap(),
    )
    .map_err(|e| format!("write aion_bundle.json: {e}"))?;

    // 2. Write Gradle project files.
    let sdk_dir = detect_android_sdk();
    if let Some(ref sdk) = sdk_dir {
        let escaped = sdk.display().to_string().replace('\\', "\\\\");
        fs::write(
            project_dir.join("local.properties"),
            format!("sdk.dir={escaped}\n"),
        )
        .map_err(|e| format!("write local.properties: {e}"))?;
    }

    fs::write(
        project_dir.join("settings.gradle.kts"),
        generate_settings_gradle(&opts.app_name),
    )
    .map_err(|e| format!("write settings.gradle.kts: {e}"))?;

    fs::write(
        project_dir.join("build.gradle.kts"),
        "// Generated by AION compiler\n",
    )
    .map_err(|e| format!("write build.gradle.kts: {e}"))?;

    fs::write(
        project_dir.join("gradle.properties"),
        "org.gradle.jvmargs=-Xmx2048m -Dfile.encoding=UTF-8\n",
    )
    .map_err(|e| format!("write gradle.properties: {e}"))?;

    fs::write(
        app_dir.join("build.gradle.kts"),
        generate_app_build_gradle(opts),
    )
    .map_err(|e| format!("write app/build.gradle.kts: {e}"))?;

    fs::write(
        app_dir.join("src/main/AndroidManifest.xml"),
        generate_manifest(&opts.app_name),
    )
    .map_err(|e| format!("write AndroidManifest.xml: {e}"))?;

    fs::write(
        java_dir.join("MainActivity.java"),
        generate_main_activity_java(&opts.app_id),
    )
    .map_err(|e| format!("write MainActivity.java: {e}"))?;

    let mode = if opts.debug { "debug" } else { "release" }.to_string();

    if opts.generate_only {
        return Ok(AndroidBuildResult {
            ok: true,
            app_id: opts.app_id.clone(),
            app_name: opts.app_name.clone(),
            version_code: opts.version_code,
            version_name: opts.version_name.clone(),
            project_dir: project_dir.display().to_string(),
            bundle_json_path: bundle_json_path.display().to_string(),
            aab_path: None,
            aab_size_bytes: None,
            mode,
        });
    }

    // 3. Locate Android SDK, JDK, and Gradle to assemble the `.aab`.
    let sdk = sdk_dir.ok_or_else(|| {
        "Android SDK not found. Set ANDROID_HOME or install Android SDK in ~/Library/Android/sdk."
            .to_string()
    })?;
    let java_home = detect_java_home().ok_or_else(|| {
        "JDK 17+ not found. Set JAVA_HOME or install Android Studio (JBR).".to_string()
    })?;
    let gradle_bin = detect_gradle_bin().ok_or_else(|| {
        "Gradle binary not found on PATH or in ~/.gradle/wrapper/dists. Install gradle or run a Gradle wrapper once."
            .to_string()
    })?;

    let task = if opts.debug {
        ":app:bundleDebug"
    } else {
        ":app:bundleRelease"
    };

    let output = Command::new(&gradle_bin)
        .current_dir(project_dir)
        .env("JAVA_HOME", &java_home)
        .env("ANDROID_HOME", &sdk)
        .env("ANDROID_SDK_ROOT", &sdk)
        .arg(task)
        .arg("--no-daemon")
        .output()
        .map_err(|e| format!("failed to run gradle `{}`: {e}", gradle_bin.display()))?;

    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        let stdout = String::from_utf8_lossy(&output.stdout);
        return Err(format!(
            "Gradle `{task}` failed (exit {:?}):\n{stdout}\n{stderr}",
            output.status.code()
        ));
    }

    let aab_file = if opts.debug {
        app_dir.join("build/outputs/bundle/debug/app-debug.aab")
    } else {
        app_dir.join("build/outputs/bundle/release/app-release.aab")
    };

    if !aab_file.is_file() {
        return Err(format!(
            "Gradle succeeded but expected App Bundle was not found at {}",
            aab_file.display()
        ));
    }

    let size_bytes = fs::metadata(&aab_file).map(|m| m.len()).ok();

    Ok(AndroidBuildResult {
        ok: true,
        app_id: opts.app_id.clone(),
        app_name: opts.app_name.clone(),
        version_code: opts.version_code,
        version_name: opts.version_name.clone(),
        project_dir: project_dir.display().to_string(),
        bundle_json_path: bundle_json_path.display().to_string(),
        aab_path: Some(aab_file.display().to_string()),
        aab_size_bytes: size_bytes,
        mode,
    })
}

fn validate_app_id(app_id: &str) -> Result<(), String> {
    let parts: Vec<&str> = app_id.split('.').collect();
    if parts.len() < 2
        || parts.iter().any(|p| {
            p.is_empty()
                || !p.chars().next().unwrap().is_ascii_alphabetic()
                || !p.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
        })
    {
        return Err(format!(
            "invalid Android applicationId `{app_id}` (expected e.g. `com.aion.myapp`)"
        ));
    }
    Ok(())
}

fn extract_port(program: &Program) -> Option<u16> {
    for node in &program.nodes {
        if let NodeKind::Srv(srv) = &node.kind {
            for p in &srv.props {
                if p.key == "port" {
                    if let PropValue::Int(port) = p.value {
                        return u16::try_from(port).ok();
                    }
                }
            }
        }
    }
    None
}

pub fn detect_android_sdk() -> Option<PathBuf> {
    for var in ["ANDROID_HOME", "ANDROID_SDK_ROOT"] {
        if let Ok(val) = std::env::var(var) {
            let p = PathBuf::from(val);
            if p.is_dir() {
                return Some(p);
            }
        }
    }
    if let Ok(home) = std::env::var("HOME") {
        for rel in ["Library/Android/sdk", "Android/Sdk"] {
            let p = PathBuf::from(&home).join(rel);
            if p.is_dir() {
                return Some(p);
            }
        }
    }
    if let Ok(local_app) = std::env::var("LOCALAPPDATA") {
        let p = PathBuf::from(local_app).join("Android/Sdk");
        if p.is_dir() {
            return Some(p);
        }
    }
    None
}

pub fn detect_java_home() -> Option<PathBuf> {
    if let Ok(val) = std::env::var("JAVA_HOME") {
        let p = PathBuf::from(val);
        if p.is_dir() {
            return Some(p);
        }
    }
    let candidates = [
        "/Applications/Android Studio.app/Contents/jbr/Contents/Home",
        "/Applications/Android Studio.app/Contents/jre/Contents/Home",
    ];
    for c in candidates {
        let p = PathBuf::from(c);
        if p.is_dir() {
            return Some(p);
        }
    }
    None
}

pub fn detect_gradle_bin() -> Option<PathBuf> {
    if let Ok(status) = Command::new("gradle").arg("--version").output() {
        if status.status.success() {
            return Some(PathBuf::from("gradle"));
        }
    }
    let home = std::env::var("HOME")
        .or_else(|_| std::env::var("USERPROFILE"))
        .ok()?;
    let dists = PathBuf::from(home).join(".gradle/wrapper/dists");
    if !dists.is_dir() {
        return None;
    }
    let mut found: Vec<PathBuf> = Vec::new();
    collect_gradle_bins(&dists, 0, &mut found);
    found.sort();
    found.pop()
}

fn collect_gradle_bins(dir: &Path, depth: usize, out: &mut Vec<PathBuf>) {
    if depth > 5 {
        return;
    }
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    let bin_name = if cfg!(windows) { "gradle.bat" } else { "gradle" };
    for entry in entries.flatten() {
        let p = entry.path();
        if p.is_file() && p.file_name().and_then(|n| n.to_str()) == Some(bin_name) {
            if p.parent().and_then(|d| d.file_name()).and_then(|n| n.to_str()) == Some("bin") {
                out.push(p);
            }
        } else if p.is_dir() {
            collect_gradle_bins(&p, depth + 1, out);
        }
    }
}

